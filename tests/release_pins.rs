//! The release pin generator and its check (owner §44/§45): `release-pins/manifest.json` and the vendored bundles of `release-pins/` are the
//! source, `src/api/bft/release_pins.rs` is generated from them, and this test fails on any mismatch or difference.
//!
//! * Every bundle is verified independently of the manifest's say-so: structure, every predecessor signature and link, canonical
//!   re-encoding, genesis and tip ids and epochs, the explicit name -> network mapping (mainnet 1, testnet2 4), the bundle digest.
//! * The manifest has the canonical form (sorted keys, two-space indent, trailing newline) and describes exactly the files present.
//! * Regeneration must leave no diff: `UTB_RELEASE_PINS_UPDATE=1 cargo test --test release_pins` rewrites the generated file.
//! * The bundles are byte-identical to unicitynetwork/unicity-ids#11 (head `source.commit`); if that PR's files change, the bundles and
//!   the manifest are regenerated and reviewed again. A new release must extend the previous release's checkpoint (a changed lineage or a
//!   rollback is an explicit trust decision, never regenerated silently).
#![cfg(feature = "std")]

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;
use sha2::{Digest, Sha256};
use unicity_token::api::bft::trust_base_cache::{PinSpec, RELEASE_PINS};
use unicity_token::api::bft::trust_base_history::BundleLimits;
use unicity_token::api::bft::TrustBaseHistory;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

const GENERATED: &str = "src/api/bft/release_pins.rs";
/// The networks a release may carry, by name: an explicit mapping, never derived from the bundle.
const NETWORKS: [(&str, u64); 2] = [("mainnet", 1), ("testnet2", 4)];

fn hexs(b: &[u8]) -> String {
    hex::encode(b)
}

fn rust_bytes(b: &[u8]) -> String {
    let mut s = String::from("[");
    for (i, x) in b.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        write!(s, "0x{x:02x}").unwrap();
    }
    s.push(']');
    s
}

/// Verify every network of the manifest and render the generated table.
fn generate(manifest_text: &str) -> Result<String, String> {
    let m: Value = serde_json::from_str(manifest_text).map_err(|e| e.to_string())?;
    // canonical form: what serde_json prints for the parsed value (sorted keys) plus the trailing newline
    let canonical = format!("{}\n", serde_json::to_string_pretty(&m).unwrap());
    if canonical != manifest_text {
        return Err("manifest.json is not in the canonical form".into());
    }
    if m["version"] != 1 {
        return Err("manifest version is not 1".into());
    }
    let source = &m["source"];
    for key in ["repository", "pullRequest", "commit"] {
        if source.get(key).is_none() {
            return Err(format!("source.{key} missing"));
        }
    }
    let nets = m["networks"].as_array().ok_or("networks is not an array")?;
    if nets.len() != NETWORKS.len() {
        return Err("the manifest has to list exactly mainnet and testnet2".into());
    }
    let mut out = String::new();
    out.push_str(
        "// @generated by tests/release_pins.rs from release-pins/manifest.json (UTB_RELEASE_PINS_UPDATE=1 rewrites it); do not edit by hand.\n",
    );
    out.push_str("use super::trust_base_cache::ReleasePinRow;\n\n");
    out.push_str("#[rustfmt::skip]\npub(super) const ROWS: &[ReleasePinRow] = &[\n");
    let mut files = vec!["manifest.json".to_string()];
    for (n, (name, id)) in nets.iter().zip(NETWORKS) {
        if n["name"] != name || n["networkId"] != id {
            return Err(format!("{name}: the name/network mapping is {name} = {id}"));
        }
        let file = n["bundle"].as_str().ok_or("bundle")?;
        if file != format!("unicity-trustbase.{name}.cbor") {
            return Err(format!("{name}: unexpected bundle file name {file}"));
        }
        files.push(file.to_string());
        let bytes =
            std::fs::read(root().join("release-pins").join(file)).map_err(|e| e.to_string())?;
        let digest = hexs(&Sha256::digest(&bytes));
        if digest != n["bundleSha256"].as_str().ok_or("bundleSha256")? {
            return Err(format!(
                "{name}: the bundle digest differs from the manifest"
            ));
        }
        // the strict, independent check: every signature, link, id and epoch, from the pinned genesis
        let spec = PinSpec::from_bundle(&bytes).map_err(|e| format!("{name}: {e}"))?;
        let history = spec
            .verify(&BundleLimits::default())
            .map_err(|e| format!("{name}: {e}"))?;
        if u64::from(spec.network_id.id()) != id {
            return Err(format!(
                "{name}: the bundle is of network {}",
                spec.network_id.id()
            ));
        }
        if history.to_bundle() != bytes {
            return Err(format!(
                "{name}: the bundle is not the canonical encoding of its history"
            ));
        }
        let same = |key: &str, got: String| -> Result<(), String> {
            if n[key].as_str() == Some(got.as_str()) {
                Ok(())
            } else {
                Err(format!("{name}: {key} differs from the bundle ({got})"))
            }
        };
        same("genesisEpoch", spec.genesis_epoch.to_string())?;
        same("genesisEntryId", hexs(&spec.genesis_entry_id))?;
        same("pinnedEpoch", spec.pinned_epoch.to_string())?;
        same("pinnedEntryId", hexs(&spec.pinned_entry_id))?;
        let _: &TrustBaseHistory = &history;
        writeln!(out, "    ReleasePinRow {{ // {name}").unwrap();
        writeln!(out, "        network_id: {id},").unwrap();
        writeln!(out, "        genesis_epoch: {},", spec.genesis_epoch).unwrap();
        writeln!(
            out,
            "        genesis_entry_id: {},",
            rust_bytes(&spec.genesis_entry_id)
        )
        .unwrap();
        writeln!(out, "        pinned_epoch: {},", spec.pinned_epoch).unwrap();
        writeln!(
            out,
            "        pinned_entry_id: {},",
            rust_bytes(&spec.pinned_entry_id)
        )
        .unwrap();
        writeln!(
            out,
            "        bundle: include_bytes!(\"../../../release-pins/{file}\"),"
        )
        .unwrap();
        writeln!(
            out,
            "        bundle_sha256: {},",
            rust_bytes(&spec.bundle_sha256)
        )
        .unwrap();
        out.push_str("    },\n");
    }
    out.push_str("];\n");
    // the directory holds exactly what the manifest names
    let mut present: Vec<String> = std::fs::read_dir(root().join("release-pins"))
        .map_err(|e| e.to_string())?
        .map(|e| e.unwrap().file_name().to_string_lossy().to_string())
        .collect();
    present.sort();
    files.sort();
    if present != files {
        return Err(format!(
            "release-pins/ holds {present:?}, the manifest names {files:?}"
        ));
    }
    Ok(out)
}

#[test]
fn the_generated_table_is_what_the_manifest_and_the_bundles_say() {
    let manifest = std::fs::read_to_string(root().join("release-pins/manifest.json")).unwrap();
    let rendered = generate(&manifest).unwrap_or_else(|e| panic!("release pins: {e}"));
    let path = root().join(GENERATED);
    if std::env::var("UTB_RELEASE_PINS_UPDATE").is_ok() {
        std::fs::write(&path, &rendered).unwrap();
    }
    let on_disk = std::fs::read_to_string(&path).unwrap();
    assert_eq!(
        on_disk, rendered,
        "{GENERATED} differs from the regenerated table (UTB_RELEASE_PINS_UPDATE=1 cargo test --test release_pins)"
    );
}

#[test]
fn the_compiled_table_is_the_manifest() {
    let m: Value = serde_json::from_str(
        &std::fs::read_to_string(root().join("release-pins/manifest.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(RELEASE_PINS.len(), 2);
    for (row, n) in RELEASE_PINS.iter().zip(m["networks"].as_array().unwrap()) {
        let file = std::fs::read(
            root()
                .join("release-pins")
                .join(n["bundle"].as_str().unwrap()),
        )
        .unwrap();
        assert_eq!(u64::from(row.network_id), n["networkId"].as_u64().unwrap());
        assert_eq!(
            row.bundle,
            file.as_slice(),
            "the embedded bytes are the file's"
        );
        assert_eq!(
            hexs(&row.bundle_sha256),
            n["bundleSha256"].as_str().unwrap()
        );
        assert_eq!(
            hexs(&row.genesis_entry_id),
            n["genesisEntryId"].as_str().unwrap()
        );
        assert_eq!(
            hexs(&row.pinned_entry_id),
            n["pinnedEntryId"].as_str().unwrap()
        );
        // and every row opens: ReleasePinInvalid would be fatal at runtime
        row.to_spec()
            .unwrap()
            .verify(&BundleLimits::default())
            .unwrap();
    }
}

#[test]
fn the_generator_refuses_a_manifest_that_does_not_match() {
    let manifest = std::fs::read_to_string(root().join("release-pins/manifest.json")).unwrap();
    assert!(generate(&manifest).is_ok());
    let tamper = |from: &str, to: &str| -> String { manifest.replacen(from, to, 1) };
    let digest = "9d01b8713cab";
    let cases = [
        ("a digest", tamper(digest, "9d01b8713cac")),
        (
            "a network id",
            tamper("\"networkId\": 1", "\"networkId\": 2"),
        ),
        (
            "the names swapped",
            tamper("\"name\": \"mainnet\"", "\"name\": \"testnet2\""),
        ),
        (
            "a pinned epoch",
            tamper("\"pinnedEpoch\": \"1\"", "\"pinnedEpoch\": \"2\""),
        ),
        (
            "a pinned id",
            tamper("\"pinnedEntryId\": \"0b6f", "\"pinnedEntryId\": \"0b6e"),
        ),
        (
            "a genesis id",
            tamper("\"genesisEntryId\": \"0b6f", "\"genesisEntryId\": \"0b6e"),
        ),
        (
            "the form (one space more)",
            tamper("\"version\": 1", "\"version\":  1"),
        ),
        ("the version", tamper("\"version\": 1", "\"version\": 2")),
    ];
    for (what, text) in cases {
        assert!(generate(&text).is_err(), "{what} was accepted");
    }
}

fn block_on<F: std::future::Future>(f: F) -> F::Output {
    use std::pin::pin;
    use std::task::{Context, Poll, RawWaker, RawWakerVTable, Waker};
    fn clone(_: *const ()) -> RawWaker {
        RawWaker::new(std::ptr::null(), &VT)
    }
    fn noop(_: *const ()) {}
    static VT: RawWakerVTable = RawWakerVTable::new(clone, noop, noop, noop);
    let waker = unsafe { Waker::from_raw(RawWaker::new(std::ptr::null(), &VT)) };
    let mut cx = Context::from_waker(&waker);
    let mut f = pin!(f);
    loop {
        if let Poll::Ready(v) = f.as_mut().poll(&mut cx) {
            return v;
        }
    }
}

#[test]
fn the_built_in_table_opens_the_approved_networks_and_no_other() {
    use unicity_token::api::bft::trust_base_cache::{
        Authority, CacheError, MemoryStore, Session, SessionOptions,
    };
    use unicity_token::api::NetworkId;
    for (id, genesis) in [
        (
            1u16,
            "0b6f8143e19e2a585be3534e8f1062f36c3b9621e506158f10abfbc9a56f4e4c",
        ),
        (
            4,
            "4b49eb2bb0729051b89a48668fd6ef1fda284aad2e10b7d5f23aad4b5faef37f",
        ),
    ] {
        let (s, d) = block_on(Session::open(
            NetworkId::new(id).unwrap(),
            Authority::Release,
            MemoryStore::new(),
            SessionOptions::default(),
        ))
        .unwrap();
        assert!(d.is_empty());
        assert_eq!(s.key().0, format!("utb/v1/{id}/{genesis}/public"));
        assert_eq!(s.history().unwrap().latest().epoch, 1);
    }
    // the removed old testnet (2), the local network (3) and anything else have no release pin
    for id in [2u16, 3, 5] {
        let r = block_on(Session::open(
            NetworkId::new(id).unwrap(),
            Authority::Release,
            MemoryStore::new(),
            SessionOptions::default(),
        ));
        assert!(matches!(r, Err(CacheError::UnknownNetwork)), "network {id}");
    }
}

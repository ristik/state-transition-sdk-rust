//! A real seal of each existing network verifies through the V2 bundle that describes its live authority (owner §44/§46).
//!
//! `tests/vectors/real-seals/` holds, per network, the unicity-ids genesis as the one-entry V2 bundle `unicity-trustbase.<network>.cbor` (the file unicity-ids
//! would ship) and the answer of the network's public gateway to `get_non_inclusion_proof.v1` for a random, never-certified state id: a non-inclusion
//! proof carries a real unicity certificate, so a seal signed by the live validators. No credential is involved (reads need none). Nothing here
//! is generated by us except the random state id.
#![cfg(feature = "std")]

use unicity_token::api::bft::TrustBaseHistory;
use unicity_token::api::{NonInclusionProof, StateId};
use unicity_token::cbor::{encode_byte_string, Decoder};
use unicity_token::verify::{NonInclusionContext, NonInclusionOutcome, VerificationError};

fn read(path: &str) -> Vec<u8> {
    std::fs::read(format!(
        "{}/tests/vectors/real-seals/{path}",
        env!("CARGO_MANIFEST_DIR")
    ))
    .unwrap()
}

fn hex_of(path: &str) -> Vec<u8> {
    hex::decode(String::from_utf8(read(path)).unwrap().trim()).unwrap()
}

/// The bundle, with the EntryID of unicity-ids' genesis as the pin.
fn history(network: &str, entry_id: &str) -> TrustBaseHistory {
    let pin: [u8; 32] = hex::decode(entry_id).unwrap().try_into().unwrap();
    TrustBaseHistory::from_bundle(
        &read(&format!("unicity-trustbase.{network}.cbor")),
        Some(pin),
    )
    .unwrap()
}

fn proof(network: &str) -> (StateId, NonInclusionProof) {
    let id = hex_of(&format!("{network}.stateid.hex"));
    let state_id = StateId::from_cbor(Decoder::new(&encode_byte_string(&id))).unwrap();
    let bytes = hex_of(&format!("{network}.non-inclusion.hex"));
    let d = Decoder::new(&bytes);
    d.finish().unwrap();
    let items = d.array(Some(2)).unwrap();
    items[0].uint().unwrap();
    let proof = NonInclusionProof::from_cbor(items[1])
        .unwrap()
        .for_state(&state_id)
        .unwrap();
    (state_id, proof)
}

fn verify(network: &str, entry_id: &str) -> Result<(NonInclusionOutcome, u16), VerificationError> {
    let h = history(network, entry_id);
    let (state_id, p) = proof(network);
    // both networks are sharded; an application pins the shard it queries (here the one the gateway answered for: the verifier
    // checks that the certificate's shard is a prefix of the queried state id)
    let shard = p.unicity_certificate().shard_tree_certificate.shard.clone();
    let out =
        p.verify_for_at_snapshot(&state_id, &h, &NonInclusionContext::new().with_shard(shard))?;
    Ok((out, h.network_id().id()))
}

const TESTNET2_ID: &str = "4b49eb2bb0729051b89a48668fd6ef1fda284aad2e10b7d5f23aad4b5faef37f";
const MAINNET_ID: &str = "0b6f8143e19e2a585be3534e8f1062f36c3b9621e506158f10abfbc9a56f4e4c";

#[test]
fn a_real_testnet2_seal_verifies_through_the_v2_bundle() {
    let (out, net) = verify("testnet2", TESTNET2_ID).expect("testnet2 seal");
    let NonInclusionOutcome::AbsentAtSnapshot { snapshot, .. } = out else {
        panic!("expected absence at the snapshot")
    };
    assert_eq!(net, 4);
    assert_eq!(snapshot.network_id().id(), 4);
    println!(
        "testnet2 round {} epoch {}",
        snapshot.root_round(),
        snapshot.root_epoch()
    );
}

#[test]
fn a_real_mainnet_seal_verifies_through_the_v2_bundle() {
    let (out, net) = verify("mainnet", MAINNET_ID).expect("mainnet seal");
    let NonInclusionOutcome::AbsentAtSnapshot { snapshot, .. } = out else {
        panic!("expected absence at the snapshot")
    };
    assert_eq!(net, 1);
    assert_eq!(snapshot.network_id().id(), 1);
    println!(
        "mainnet round {} epoch {}",
        snapshot.root_round(),
        snapshot.root_epoch()
    );
}

#[test]
fn controls_another_networks_bundle_or_a_damaged_signature_do_not_verify() {
    // testnet2's seal under mainnet's bundle
    let h = history("mainnet", MAINNET_ID);
    let (state_id, p) = proof("testnet2");
    let shard = p.unicity_certificate().shard_tree_certificate.shard.clone();
    let ctx = NonInclusionContext::new().with_shard(shard);
    assert!(p.verify_for_at_snapshot(&state_id, &h, &ctx).is_err());

    // damaged signatures: the proof still decodes, but once fewer than a quorum verify the seal no longer authenticates
    let raw = hex_of("testnet2.non-inclusion.hex");
    let sigs: Vec<Vec<u8>> = p
        .unicity_certificate()
        .unicity_seal
        .signatures
        .iter()
        .map(|(_, s)| s.clone())
        .collect();
    let h4 = history("testnet2", TESTNET2_ID);
    let damaged = |n: usize| {
        let mut bad = raw.clone();
        for sig in &sigs[..n] {
            let at = bad
                .windows(sig.len())
                .position(|w| w == sig.as_slice())
                .unwrap();
            bad[at + 10] ^= 1;
        }
        let d = Decoder::new(&bad);
        let items = d.array(Some(2)).unwrap();
        let q = NonInclusionProof::from_cbor(items[1])
            .unwrap()
            .for_state(&state_id)
            .unwrap();
        let ctx = NonInclusionContext::new()
            .with_shard(q.unicity_certificate().shard_tree_certificate.shard.clone());
        q.verify_for_at_snapshot(&state_id, &h4, &ctx).map(|_| ())
    };
    assert!(sigs.len() >= 4);
    assert_eq!(damaged(0), Ok(()));
    assert!(damaged(sigs.len()).is_err(), "no valid signature");
    assert!(
        damaged(sigs.len() - 1).is_err(),
        "one valid signature of four is below the quorum"
    );
}
